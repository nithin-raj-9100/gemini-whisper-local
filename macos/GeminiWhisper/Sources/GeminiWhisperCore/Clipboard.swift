#if canImport(AppKit)
import AppKit
import Foundation

/// Snapshot of pasteboard items, including non-string flavors, for save/restore around paste.
public struct ClipboardSnapshot: Equatable, Sendable {
    public struct Item: Equatable, Sendable {
        public var representations: [String: Data]

        public init(representations: [String: Data]) {
            self.representations = representations
        }
    }

    public var items: [Item]

    public init(items: [Item]) {
        self.items = items
    }

    /// Markers from nspasteboard.org that clipboard managers (Maccy, Raycast,
    /// Alfred, Paste, ...) honor: the temporary transcript and the restore of the
    /// user's own clipboard are not recorded as new history entries.
    public static let transientTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    public static func capture(_ pasteboard: NSPasteboard = .general) -> ClipboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            var representations: [String: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) {
                    representations[type.rawValue] = data
                }
            }
            return Item(representations: representations)
        }
        return ClipboardSnapshot(items: items)
    }

    /// Replaces the pasteboard with `text` and returns a snapshot that can restore the previous contents.
    @discardableResult
    public static func replaceString(_ text: String, on pasteboard: NSPasteboard = .general) -> ClipboardSnapshot {
        let snapshot = capture(pasteboard)
        writeTransientString(text, to: pasteboard)
        return snapshot
    }

    /// Writes `text` marked as transient, without taking a snapshot.
    public static func writeTransientString(_ text: String, to pasteboard: NSPasteboard = .general) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in transientTypes {
            item.setData(Data(), forType: type)
        }
        pasteboard.writeObjects([item])
    }

    public func restore(to pasteboard: NSPasteboard = .general) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }
        let objects: [NSPasteboardItem] = items.map { item in
            let pbItem = NSPasteboardItem()
            for (rawType, data) in item.representations {
                pbItem.setData(data, forType: NSPasteboard.PasteboardType(rawType))
            }
            for type in Self.transientTypes where item.representations[type.rawValue] == nil {
                pbItem.setData(Data(), forType: type)
            }
            return pbItem
        }
        pasteboard.writeObjects(objects)
    }

    /// Restores only while the pasteboard still holds what this app wrote, as
    /// identified by its change count. Anything the user copied in the meantime
    /// wins. Returns whether the restore happened.
    @discardableResult
    public func restore(to pasteboard: NSPasteboard = .general, ifChangeCount expected: Int) -> Bool {
        guard pasteboard.changeCount == expected else { return false }
        restore(to: pasteboard)
        return true
    }
}
#endif
